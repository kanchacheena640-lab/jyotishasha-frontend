export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const locale = toLocale(params.locale);
  const title = COPY.title[locale];
  const description = COPY.description[locale];
  const canonical = pageUrl(locale);
  return {
    title,
    description,
    alternates: {
      canonical,
      languages: { en: pageUrl("en"), hi: pageUrl("hi"), "x-default": pageUrl("en") },
    },
    openGraph: {
      title,
      description,
      url: canonical,
      type: "website",
      siteName: "Jyotishasha",
      locale: locale === "hi" ? "hi_IN" : "en_IN",
      images: [{ url: DEFAULT_OG_IMAGE, width: 1730, height: 909, alt: title }],
    },
  };
}

